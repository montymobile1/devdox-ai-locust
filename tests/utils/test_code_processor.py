class TestExtractCode:
    """Tests for extract_code and its helpers."""

    def test_extract_from_code_tags(self, processor):
        response = "<code>print('hello')</code>"
        assert processor.extract_code(response) == "print('hello')"

    def test_extract_from_code_tags_with_attributes(self, processor):
        response = '<code lang="python">print("hi")</code>'
        assert processor.extract_code(response) == 'print("hi")'

    def test_extract_ignores_analysis_tags(self, processor):
        response = "<analysis>Some reasoning</analysis><code>x = 1</code>"
        assert processor.extract_code(response) == "x = 1"

    def test_extract_strips_markdown_fences(self, processor):
        response = "<code>```python\nprint('hi')\n```</code>"
        assert processor.extract_code(response) == "print('hi')"

    def test_extract_unclosed_code_tag(self, processor):
        response = "<code>x = 1\ny = 2"
        result = processor.extract_code(response)
        assert "x = 1" in result
        assert "y = 2" in result

    def test_extract_plain_code_no_tags(self, processor):
        response = "x = 1\ny = 2"
        assert processor.extract_code(response) == "x = 1\ny = 2"

    def test_extract_picks_longest_code_block(self, processor):
        response = "<code>short</code><code>this is longer code</code>"
        assert processor.extract_code(response) == "this is longer code"

    def test_extract_removes_commentary_lines(self, processor):
        response = "<code>x = 1\nNote: this is a note\ny = 2</code>"
        result = processor.extract_code(response)
        assert "x = 1" in result
        assert "Note:" not in result
        assert "y = 2" in result

    @pytest.mark.parametrize(
        "line",
        [
            "!pip install locust",
            "DO NOT EDIT this file",
            "generated by AI",
            "Note: something",
            "Note that this",
            "Since we need to",
            "This endpoint does",
            "This is a test",
            "We test the endpoint",
            "STEP 1: do something",
            "Method: GET",
            "Path: /users",
            "Required: yes",
            "Optional: no",
        ],
    )
    def test_remove_commentary_lines_filters(self, processor, line):
        response = f"<code>x = 1\n{line}\ny = 2</code>"
        result = processor.extract_code(response)
        assert line not in result

    def test_remove_commentary_preserves_since_function_call(self, processor):
        response = "<code>Since(x)</code>"
        result = processor.extract_code(response)
        assert "Since(x)" in result


class TestFixClassName:
    """Tests for fix_class_name."""

    def test_fixes_wrong_class_name(self, processor):
        code = "class WrongName(BaseWorkflow):\n    pass"
        result = processor.fix_class_name(code, "Users", "positive")
        assert "class UsersPositiveWorkflow(BaseWorkflow):" in result

    def test_preserves_correct_class_name(self, processor):
        code = "class UsersPositiveWorkflow(BaseWorkflow):\n    pass"
        result = processor.fix_class_name(code, "Users", "positive")
        assert "class UsersPositiveWorkflow(BaseWorkflow):" in result

    def test_no_class_found_returns_unchanged(self, processor):
        code = "x = 1\ny = 2"
        result = processor.fix_class_name(code, "Users", "positive")
        assert result == code

    def test_scenario_type_capitalized(self, processor):
        code = "class Foo(BaseWorkflow):\n    pass"
        result = processor.fix_class_name(code, "Auth", "security")
        assert "class AuthSecurityWorkflow(BaseWorkflow):" in result


